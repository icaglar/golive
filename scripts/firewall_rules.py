#!/usr/bin/env python3
"""Print Hetzner Cloud Firewall rules (JSON, API format) for a web server behind Cloudflare.

- 80/443 only from Cloudflare's published IP ranges (fetched live; a built-in
  copy is used, with a warning, if cloudflare.com is unreachable). Use --public
  to open 80/443 to everyone instead (no Cloudflare proxy).
- 22 from --ssh-from (repeatable). Defaults to everywhere, with a warning.
- ICMP in, so ping and path MTU discovery work.

Usage:
  firewall_rules.py [--ssh-from 203.0.113.7/32] [--public] > rules.json
  hcloud firewall create --name golive-web --rules-file rules.json

Other formats (--format):
  hetzner      Hetzner Cloud Firewall rules JSON (default)
  cidr-list    plain lists of the web and SSH source ranges, for any provider's cloud firewall
  docker-user  a bash script with iptables/ip6tables rules in Docker's DOCKER-USER chain, so
               ports published by Docker (which bypass ufw) only accept Cloudflare; for servers
               without a cloud firewall. Install it as a oneshot systemd unit after docker.service.
  json-ranges  {"v4": [...], "v6": [...], "caddy_trusted_proxies": "<space separated>"} of Cloudflare's
               ranges only (ignores --ssh-from/--public); used to compare against a saved copy
               (templates/firewall/) and to refresh Caddy's trusted_proxies list.
"""
import argparse
import ipaddress
import json
import sys
import urllib.request

# Snapshot of https://www.cloudflare.com/ips-v4 and /ips-v6, used only as a fallback.
FALLBACK_V4 = [
    "173.245.48.0/20", "103.21.244.0/22", "103.22.200.0/22", "103.31.4.0/22",
    "141.101.64.0/18", "108.162.192.0/18", "190.93.240.0/20", "188.114.96.0/20",
    "197.234.240.0/22", "198.41.128.0/17", "162.158.0.0/15", "104.16.0.0/13",
    "104.24.0.0/14", "172.64.0.0/13", "131.0.72.0/22",
]
FALLBACK_V6 = [
    "2400:cb00::/32", "2606:4700::/32", "2803:f800::/32", "2405:b500::/32",
    "2405:8100::/32", "2a06:98c0::/29", "2c0f:f248::/32",
]
EVERYWHERE = ["0.0.0.0/0", "::/0"]


def fetch_ranges(url):
    req = urllib.request.Request(url, headers={"User-Agent": "golive/0.1"})
    with urllib.request.urlopen(req, timeout=10) as resp:
        lines = resp.read().decode().split()
    nets = [str(ipaddress.ip_network(line.strip())) for line in lines if line.strip()]
    if not nets:
        raise ValueError("empty list")
    return nets


def cloudflare_ranges():
    try:
        return fetch_ranges("https://www.cloudflare.com/ips-v4") + fetch_ranges("https://www.cloudflare.com/ips-v6"), True
    except Exception as e:
        print(f"warning: could not fetch Cloudflare ranges ({e.__class__.__name__}); using the built-in copy", file=sys.stderr)
        return FALLBACK_V4 + FALLBACK_V6, False


def rule(port, sources, description, protocol="tcp"):
    r = {"direction": "in", "protocol": protocol, "source_ips": sources, "description": description}
    if port:
        r["port"] = port
    return r


def docker_user_script(sources):
    v4 = [c for c in sources if ":" not in c]
    v6 = [c for c in sources if ":" in c]
    return f"""#!/usr/bin/env bash
# generated by golive firewall_rules.py --format docker-user
# Only Cloudflare may reach ports 80/443 published by Docker. Re-run safe: old golive rules are removed first.
set -euo pipefail
apply() {{
  local ipt=$1; shift
  {{ $ipt -S DOCKER-USER 2>/dev/null || true; }} | {{ grep -- '--comment golive' || true; }} | sed 's/^-A /-D /' | while read -r rule; do
    eval "$ipt $rule"
  done
  for port in 80 443; do
    $ipt -I DOCKER-USER -p tcp -m conntrack --ctorigdstport "$port" --ctdir ORIGINAL -m comment --comment golive -j DROP
    for cidr in "$@"; do
      $ipt -I DOCKER-USER -p tcp -s "$cidr" -m conntrack --ctorigdstport "$port" --ctdir ORIGINAL -m comment --comment golive -j RETURN
    done
  done
}}
apply iptables {" ".join(v4)}
apply ip6tables {" ".join(v6)}
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ssh-from", action="append", default=[], help="CIDR allowed to SSH (repeatable)")
    ap.add_argument("--ssh-port", default="22", help="SSH port for the SSH rule (default 22)")
    ap.add_argument("--public", action="store_true", help="open 80/443 to everyone instead of Cloudflare only")
    ap.add_argument("--format", choices=["hetzner", "cidr-list", "docker-user", "json-ranges"], default="hetzner")
    args = ap.parse_args()

    if args.format == "json-ranges":
        nets, _ = cloudflare_ranges()
        v4 = sorted(c for c in nets if ":" not in c)
        v6 = sorted(c for c in nets if ":" in c)
        json.dump({"v4": v4, "v6": v6, "caddy_trusted_proxies": " ".join(v4 + v6)}, sys.stdout, indent=2)
        print()
        return

    ssh_sources = [str(ipaddress.ip_network(c, strict=False)) for c in args.ssh_from] or EVERYWHERE
    if not args.ssh_from:
        print("warning: SSH open to everyone; pass --ssh-from <your-ip>/32 to restrict it", file=sys.stderr)

    if args.public:
        web_sources, label = EVERYWHERE, "everyone"
    else:
        web_sources, _ = cloudflare_ranges()
        label = "Cloudflare only"

    if args.format == "cidr-list":
        print(f"# web 80/443 ({label})")
        print("\n".join(web_sources))
        print(f"# ssh {int(args.ssh_port)}")
        print("\n".join(ssh_sources))
        return
    if args.format == "docker-user":
        if args.public:
            print("# --public: nothing to restrict; Docker-published 80/443 stay open to everyone")
            return
        print(docker_user_script(web_sources), end="")
        return

    rules = [
        rule(str(int(args.ssh_port)), ssh_sources, "SSH"),
        rule("80", web_sources, f"HTTP ({label})"),
        rule("443", web_sources, f"HTTPS ({label})"),
        rule(None, EVERYWHERE, "ICMP", protocol="icmp"),
    ]
    json.dump(rules, sys.stdout, indent=2)
    print()


if __name__ == "__main__":
    main()
